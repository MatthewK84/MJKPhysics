//! The generated page of an airframe ([#18](https://github.com/MatthewK84/MJKPhysics/issues/18)):
//! every parameter with its value as written, its unit, its value in SI units, its uncertainty
//! and its source, so the book cannot disagree with what the simulator loads.

use std::collections::BTreeMap;

use super::airframe::{Airframe, LoadedAirframe};
use super::mass::ComponentConfig;
use super::parameter::{ConfigWarning, ParameterRecord, significant};
use super::plausibility::thrust_to_weight;
use super::rotors::Rotor;
use super::sources::Source;

/// The airframe's page, in Markdown.
#[must_use]
pub fn airframe_page(loaded: &LoadedAirframe) -> String {
    [
        summary(&loaded.airframe),
        rotors(&loaded.airframe.rotors),
        parts(&loaded.config.mass.components),
        parameters(&loaded.parameters),
        sources(&loaded.config.sources),
        warnings(&loaded.warnings),
    ]
    .concat()
}

/// Text safe inside a table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

fn summary(airframe: &Airframe) -> String {
    let mass = &airframe.mass;
    let cg: Vec<String> = mass.cg_m().to_array().map(significant).to_vec();
    let diagonal: Vec<String> = mass.inertia_kg_m2().diagonal().map(significant).to_vec();
    format!(
        "# {}\n\n\
         *Generated by `mjk airframe` from the airframe's file. A test fails if this page no \
         longer matches the file.*\n\n\
         | Quantity | Value |\n|---|---|\n\
         | Mass | {} kg |\n\
         | Center of mass | [{}] m |\n\
         | Inertia, diagonal | [{}] kg·m² |\n\
         | Rotors | {} |\n\
         | Thrust-to-weight | {} |\n\n",
        cell(&airframe.name),
        significant(mass.mass_kg()),
        cg.join(", "),
        diagonal.join(", "),
        airframe.rotors.len(),
        significant(thrust_to_weight(airframe)),
    )
}

fn rotors(rotors: &[Rotor]) -> String {
    let rows: Vec<String> = rotors
        .iter()
        .enumerate()
        .map(|(index, rotor)| {
            let position = rotor.position_m.to_array().map(significant).join(", ");
            let axis = rotor.axis.to_array().map(significant).join(", ");
            let [motor, esc] = [&rotor.motor, &rotor.esc].map(|key| {
                key.as_ref()
                    .map_or_else(|| "—".to_owned(), |key| format!("`{}`", cell(key)))
            });
            format!(
                "| {index} | {} | [{position}] m | [{axis}] | {} | `{}` | {motor} | {esc} |\n",
                cell(&rotor.name),
                rotor.spin.name(),
                cell(&rotor.propeller),
            )
        })
        .collect();
    format!(
        "## Rotors\n\n\
         Spin is seen from the side the thrust points to.\n\n\
         | # | Name | Hub | Thrust axis | Spin | Propeller | Motor | ESC |\n\
         |---:|---|---|---|---|---|---|---|\n{}\n",
        rows.concat()
    )
}

fn parts(components: &[ComponentConfig]) -> String {
    if components.is_empty() {
        return String::new();
    }
    let rows: Vec<String> = components
        .iter()
        .enumerate()
        .map(|(index, part)| {
            format!(
                "| {index} | {} | {} |\n",
                cell(&part.name),
                part.shape.name()
            )
        })
        .collect();
    format!(
        "## Parts\n\n\
         The mass properties are built up from these parts: `mass.components[#]` below.\n\n\
         | # | Part | Shape |\n|---:|---|---|\n{}\n",
        rows.concat()
    )
}

fn parameters(records: &[ParameterRecord]) -> String {
    let rows: Vec<String> = records
        .iter()
        .map(|record| {
            format!(
                "| `{}` | {} | `{}` | {} | {} | {} |\n",
                cell(&record.path.to_string()),
                record.value,
                cell(&record.unit),
                record.si,
                record
                    .uncertainty
                    .as_ref()
                    .map_or_else(|| "—".to_owned(), |u| format!("±{u}")),
                record
                    .source
                    .as_ref()
                    .map_or_else(|| "**none**".to_owned(), |key| format!("`{}`", cell(key))),
            )
        })
        .collect();
    format!(
        "## Parameters\n\n\
         | Parameter | Value | Unit | SI | Uncertainty | Source |\n\
         |---|---:|---|---:|---:|---|\n{}\n",
        rows.concat()
    )
}

fn sources(sources: &BTreeMap<String, Source>) -> String {
    let rows: Vec<String> = sources
        .iter()
        .map(|(key, source)| format!("| `{}` | {} |\n", cell(key), cell(&source.citation())))
        .collect();
    format!(
        "## Sources\n\n| Key | Source |\n|---|---|\n{}",
        rows.concat()
    )
}

fn warnings(warnings: &[ConfigWarning]) -> String {
    if warnings.is_empty() {
        return String::new();
    }
    let lines: Vec<String> = warnings
        .iter()
        .map(|warning| format!("- `{}`: {}\n", warning.path, warning.message))
        .collect();
    format!("\n## Warnings\n\n{}", lines.concat())
}
